"""
File 2: geometry.py
Defines geometric calculations: area and perimeter of a circle.
"""

def area_of_circle(radius):
    """Calculates and returns the area of a circle given its radius."""
    return 3.14 * radius * radius

def perimeter_of_circle(radius):
    """Calculates and returns the perimeter (circumference) of a circle given its radius."""
    return 2 * 3.14 * radius
